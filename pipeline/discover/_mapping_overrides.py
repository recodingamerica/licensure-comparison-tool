"""Shared loader/applier for config/mapping_overrides.yaml — manual patches to
the generated profession_index.

The committed results/profession_index/<prof>.json files are a PURE FUNCTION of
committed inputs: hierarchies + professions.yaml + state_structure.yaml + this
file. Anything the generator's rules can't reproduce (missed-match recalls,
LLM-mapped chapters, section-match containers, the old gitignored
section_map/chapter_map fallout) lives here as per-profession/per-state
`exclude` urls and verbatim `add` nodes, applied as the LAST transformation in
match_profession.build_index_for. Never hand-edit the index JSON — edit this
YAML (or state_structure.yaml) and re-run the matcher; the gate is
pipeline.eval.verify_index_reproducibility.

Shape:
    <profession>:
      <STATE>:
        exclude:            # optional: url strings to REMOVE from the generated list
          - https://law.justia.com/...
        add:                # optional: node dicts appended VERBATIM (all keys preserved)
          - label: "..."
            url: https://...
            slug: chapter-25
            via: missed_match_recall
"""

from __future__ import annotations

import logging

from pipeline.discover._url import _abs_url
from pathlib import Path

import yaml

from pipeline.paths import CONFIG_DIR
from pipeline.config.yaml_loader import safe_load_unique

OVERRIDES_PATH = CONFIG_DIR / "mapping_overrides.yaml"

log = logging.getLogger("mapping_overrides")

# Emitted at the top of every write so read-modify-write helpers keep the provenance note.
_HEADER = """\
# mapping_overrides.yaml — manual patches to the generated profession_index.
#
# Generated by pipeline.discover.migrate_mapping_overrides on 2026-07-01 (folding the
# hand-injected / section_map_v2 / chapter_map residual out of the committed index
# JSON); hand-maintained since. Entries patch the generated index AFTER all other
# rules (label match, state_structure overrides, umbrella, chapter_url_template):
# `exclude` urls are dropped from the generated list, then `add` nodes are appended
# verbatim. Provenance for each add lives in its `via` tag.
#
# Gate: pipeline/.venv/bin/python -m pipeline.eval.verify_index_reproducibility
"""


def load_mapping_overrides() -> dict:
    """Load config/mapping_overrides.yaml. Returns {} if missing.

    Uses safe_load_unique so a duplicate profession/state key is a hard error
    (silent last-wins would drop a whole block of patches — see yaml_loader.py).
    """
    if not OVERRIDES_PATH.exists():
        return {}
    return safe_load_unique(OVERRIDES_PATH.read_text()) or {}


def apply_override_adds(profession: str, state: str, matched: list[dict], overrides: dict) -> list[dict]:
    """Append one profession/state's `add` nodes to a generated node list.

    Pure function: `matched` is not mutated. Each add node is appended verbatim —
    unless a node with the same url is already present AND dict-equal (same url
    but a different dict is appended anyway, with a warning;
    verify_index_reproducibility surfaces it).

    Called TWICE by build_index_for: once before the pruning rules (so an add
    carrying section_url_list/section_slug_pattern triggers section_fallback
    subsumption exactly like the old section_map fallbacks did), and once at the
    end (re-ensuring presence if a pruning rule ate the node — an add is a
    guarantee the node is in the final index). Idempotent by dict-equality.
    """
    entry = ((overrides.get(profession) or {}).get(state)) or {}
    out = list(matched)
    for node in entry.get("add") or []:
        # Absolutize before the dedup-by-url compare below: the hierarchy hands some
        # urls back root-relative, so an `add` node written from one ("/codes/mass/...")
        # would never equal the absolute copy already in `matched` and the index would
        # flip between the two forms on every rebuild (MA, 2026-08-03).
        node = {**node, "url": _abs_url(node.get("url", ""))}
        same_url = [x for x in out if x.get("url") == node.get("url")]
        if any(x == node for x in same_url):
            continue
        if same_url:
            log.warning(
                "mapping_overrides[%s][%s]: add url %s already present with a different dict — appending anyway",
                profession, state, node.get("url"),
            )
        out.append(dict(node))
    return out


def apply_override_excludes(profession: str, state: str, matched: list[dict], overrides: dict) -> list[dict]:
    """Drop every node whose url is in this profession/state's `exclude` list.
    Pure function; applied as the LAST transformation so an exclude is a
    guarantee the url is NOT in the final index."""
    entry = ((overrides.get(profession) or {}).get(state)) or {}
    exclude = set(entry.get("exclude") or [])
    if not exclude:
        return list(matched)
    return [n for n in matched if n.get("url") not in exclude]


def apply_mapping_overrides(profession: str, state: str, matched: list[dict], overrides: dict) -> list[dict]:
    """Excludes then adds — the end-of-pipeline composition (see the two parts
    for semantics). Kept as the single entry point for tools that patch a
    finished node list outside build_index_for."""
    out = apply_override_excludes(profession, state, matched, overrides)
    return apply_override_adds(profession, state, out, overrides)


def write_mapping_overrides(data: dict) -> None:
    """Deterministic writer: professions sorted, states sorted within a profession,
    `exclude` before `add` within a state. Empty entries are dropped."""
    ordered: dict = {}
    for prof in sorted(data):
        states = data[prof] or {}
        prof_out: dict = {}
        for st in sorted(states):
            entry = states[st] or {}
            state_out: dict = {}
            if entry.get("exclude"):
                state_out["exclude"] = list(entry["exclude"])
            if entry.get("add"):
                state_out["add"] = list(entry["add"])
            if state_out:
                prof_out[st] = state_out
        if prof_out:
            ordered[prof] = prof_out
    body = yaml.safe_dump(ordered, allow_unicode=True, sort_keys=False, width=1000)
    OVERRIDES_PATH.write_text(_HEADER + body)


def add_override_entry(profession: str, state: str, node: dict) -> None:
    """Append one `add` node for profession/state (read-modify-write). Idempotent:
    an identical node already present is a no-op."""
    data = load_mapping_overrides()
    entry = data.setdefault(profession, {}).setdefault(state, {})
    adds = entry.setdefault("add", [])
    if any(x == node for x in adds):
        return
    adds.append(node)
    write_mapping_overrides(data)


def add_exclude_entry(profession: str, state: str, url: str) -> None:
    """Append one `exclude` url for profession/state (read-modify-write). Idempotent."""
    data = load_mapping_overrides()
    entry = data.setdefault(profession, {}).setdefault(state, {})
    excludes = entry.setdefault("exclude", [])
    if url in excludes:
        return
    excludes.append(url)
    write_mapping_overrides(data)
